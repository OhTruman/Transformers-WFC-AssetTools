"""Generic multiplayer map pipeline: choose a map -> run every stage -> canonical manifest + completeness report.

  python run_map_pipeline.py MP_UND_Gorge [--cap-gb 6] [--allow-streets]

Every stage runs through run_bounded.py (Windows Job Object memory cap); stages run one at a time and a lock file
(logs/map_pipeline.lock) refuses overlapping pipelines. MP_IAC_Streets is refused unless --allow-streets: its validated
outputs are regenerated by the Streets-specific order in CLAUDE.md (vs_map vs_collision vs_physics vs_validate, m04_*, ...).
Outputs: ExtractedAssets/VerticalSlice/Maps/<MAP>/, manifests/next_map/<MAP>_*.json, manifests/maps/<MAP>/{map_complete,
render_index_generic,completeness}.json; stage log + summary in logs/<MAP>_pipeline/ and manifests/next_map/<MAP>_probe.json.
"""
import argparse, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
AT = os.path.normpath(os.path.join(HERE, '..', '..'))
STAGES = [['vs_map.py', '{M}'], ['vs_lighting.py', '{M}'], ['vs_postprocess.py', '{M}'], ['vs_navigation.py', '{M}'],
          ['m04_lightmap_atlases.py', '{M}'], ['vs_lightmap.py', '{M}'], ['vs_materials.py', '{M}'], ['vs_props.py', '{M}'],
          ['vs_collision.py', '{M}'], ['vs_physics.py', '{M}'], ['vs_gameplay.py', '{M}'], ['vs_audio.py', '{M}'], ['vs_mapfx.py', '{M}'],
          ['m04_inventory.py', '{M}'], ['validate_smca_transforms.py', '--map', '{M}'], ['vs_validate.py', '{M}'], ['map_complete.py', '{M}']]

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('map'); ap.add_argument('--cap-gb', type=float, default=6.0)
    ap.add_argument('--allow-streets', action='store_true'); a = ap.parse_args()
    if a.map == 'MP_IAC_Streets' and not a.allow_streets:
        sys.exit('refusing MP_IAC_Streets: use the Streets regeneration order in CLAUDE.md (or --allow-streets)')
    lock = os.path.join(AT, 'logs', 'map_pipeline.lock')
    os.makedirs(os.path.dirname(lock), exist_ok=True)
    if os.path.exists(lock):
        sys.exit('another map pipeline is running (%s): %s' % (lock, open(lock).read()))
    open(lock, 'w').write('%s pid %d started %s' % (a.map, os.getpid(), time.ctime()))
    logdir = os.path.join(AT, 'logs', a.map + '_pipeline')
    os.makedirs(logdir, exist_ok=True)
    for f in os.listdir(logdir): os.remove(os.path.join(logdir, f))
    failed = None
    try:
        for i, st in enumerate(STAGES, 1):
            args = [x.replace('{M}', a.map) for x in st]
            log = os.path.join(logdir, '%02d_%s.log' % (i, st[0][:-3]))
            r = subprocess.run([sys.executable, os.path.join(HERE, 'run_bounded.py'), '--cap-gb', str(a.cap_gb), '--log', log, '--',
                                os.path.join(HERE, args[0])] + args[1:], cwd=AT, capture_output=True, text=True)
            print((r.stdout.strip().splitlines() or ['?'])[-1][:160])
            if r.returncode != 0:
                failed = st[0]; break
    finally:
        os.remove(lock)
    subprocess.run([sys.executable, os.path.join(HERE, 'next_map_probe_summary.py'), a.map, os.path.relpath(logdir, AT)], cwd=AT)
    print('pipeline', a.map, 'FAILED at ' + failed if failed else 'OK')
    sys.exit(1 if failed else 0)

if __name__ == '__main__':
    main()
