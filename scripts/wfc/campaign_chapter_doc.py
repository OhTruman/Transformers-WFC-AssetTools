"""Per-chapter campaign pilot doc (Integration format: stages with wall time / peak memory, exports, completeness, streaming, blockers,
materials list for Rendering). Reads only outputs of a finished run_campaign.cmd: logs/<MAP>_pipeline/*.log, the chapter's
WFC_VS_ROOT map folder, manifests/maps/<MAP>/, manifests/next_map/<MAP>_*, inventory.db, the RE decomp file list.

  python campaign_chapter_doc.py <MAP> [notes.md]   -> docs/handoff/CAMPAIGN_PILOT_<MAP>.md + work/campaign_pilot/<MAP>_materials_for_rendering.json
"""
import glob, json, os, re, sqlite3, sys, time
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__)); AT = os.path.dirname(os.path.dirname(HERE)); REB = os.path.dirname(AT)
sys.path.insert(0, HERE)
VSR = os.path.join(AT, 'work', 'campaign_pilot', 'VerticalSlice')
CAP_GB = 10.0

def stages(M):
    rows = {}
    for f in sorted(glob.glob(os.path.join(AT, 'logs', M + '_pipeline', '*.log')), key=os.path.getmtime):
        m = [l for l in open(f, encoding='utf-8', errors='replace') if l.startswith('run_bounded:')]
        if not m: continue
        x = re.search(r'rc=(-?\d+)\s+wall=([\d.]+)s\s+peak_job_memory=([\d.]+) GB.*cmd=.*?([\w]+)\.py', m[-1])
        if not x: continue
        rows[x.group(4)] = (int(x.group(1)), float(x.group(2)), float(x.group(3)))     # last run of each stage wins
    return rows

def main(M, notes=None):
    md = os.path.join(VSR, 'Maps', M); mj = json.load(open(os.path.join(md, 'map.json'), encoding='utf-8'))
    st = json.load(open(os.path.join(md, 'streaming.json'), encoding='utf-8'))
    comp = json.load(open(os.path.join(AT, 'manifests', 'maps', M, 'completeness.json'), encoding='utf-8'))
    nav = json.load(open(os.path.join(md, 'navigation.json'), encoding='utf-8'))
    S = stages(M); subs = mj['sublevels']
    order = ['vs_map', 'vs_lighting', 'vs_light_probes', 'vs_postprocess', 'vs_navigation', 'vs_lightmap', 'm04_lightmap_atlases',
             'vs_vertex_lightmaps', 'vs_vertex_remap', 'vs_materials', 'vs_props', 'vs_collision', 'vs_physics', 'vs_gameplay', 'vs_audio',
             'vs_mapfx', 'm04_inventory', 'validate_smca_transforms', 'vs_validate', 'm04_bsp', 'm05_bsp_default_faces', 'm04_kismet',
             'vs_pickups', 'vs_destructibles', 'vs_surface_audio', 'map_structure_audit', 'map_complete', 'map_render_index', 'vs_streaming']
    total = sum(S[s][1] for s in S); peak = max((S[s][2] for s in S), default=0)
    L = []; a = L.append
    a('# Campaign pilot: %s through the generic map pipeline (%s, PROVISIONAL)\n' % (M, time.strftime('%Y-%m-%d')))
    a('Generated by `scripts/wfc/campaign_chapter_doc.py` from the run\'s logs and outputs. Rules: CPU only, `run_bounded.py` per stage '
      '(refuses while any PERF_HOLD exists, cap %.0f GB), `hold_wait.cmd` before launch; outputs under `AssetTools/work/campaign_pilot/'
      'VerticalSlice/Maps/%s/` via `WFC_VS_ROOT`; ExtractedAssets / Game Dump not written. authored.db rows re-parsed before this run '
      '(parser fix f384c7b).\n' % (CAP_GB, M))
    lg = os.path.join(AT, 'work', 'campaign_pilot', M + '.log')
    hdr = open(lg, encoding='utf-8', errors='replace').readline().strip() if os.path.exists(lg) else ''
    pc = re.search(r'pkgcache (\d+)', hdr)
    a('Run: `%s`; package cache WFC_PKG_CACHE = %s (MP default 16).\n' % (hdr, pc.group(1) if pc else '16 (default; run before the setting existed)'))
    a('## 1. Stages\n\n| stage | rc | wall | peak GB |\n|---|---|---|---|')
    for s in order:
        if s in S:
            rc, w, p = S[s]
            flag = ' **CAP HIT**' if p >= CAP_GB - 0.01 else ''
            a('| %s | %s | %.1f s | %.2f%s |' % (s, 'OK' if rc == 0 else 'rc %d' % rc, w, p, flag))
    a('\nTotal wall %.1f min; peak %.2f GB. Stage failures: %s.\n' % (total / 60, peak, ', '.join(s for s in S if S[s][0] != 0) or 'none'))
    cc = Counter(v.get('status') for v in comp['checks'].values())
    a('## 2. Export and completeness\n')
    a('- Completeness **%s**: %d checks, %s.' % (comp['status'], len(comp['checks']), ', '.join('%d %s' % (n, k) for k, n in cc.most_common())))
    for k, v in comp['checks'].items():
        if v.get('status') not in ('COMPLETE', 'PASS'):
            a('  - %s: %s %s' % (k, v.get('status'), json.dumps(v.get('evidence'), default=str)[:200]))
    bsp = sum((v or {}).get('render_triangles') or 0 for v in mj['bsp'].values())
    a('- %d levels (%s); %d placed meshes (%d unique, %d without mesh); %d BSP triangles; %d lights; %d volumes; %d emitters.' % (
        len(subs), ', '.join('%d %s' % (n, k) for k, n in Counter(v['kind'] for v in st['sublevels'].values()).most_common()),
        mj['placed_props'], mj['unique_meshes'], mj['props_missing_mesh'], bsp, mj['lights'], mj['volumes'], mj['emitters']))
    a('- Gameplay points: %s.' % json.dumps(mj['spawn_and_gameplay_points']))
    a('- Navigation: %s nodes, %s edges.' % (len(nav.get('nodes') or []), len(nav.get('edges') or [])))
    a('- Streaming (`streaming.json`): %d authored states, initial `%s`; %d SetStreamingState actions; %d checkpoint references; %d flush '
      'actions; %d world.glb nodes tagged (%d ambiguous, candidates listed). CINE sublevels (hidden outside matinee): %s.\n' % (
        len(st['states']), st['initial_state'], sum(len(s['set_by']) for s in st['states']), sum(len(s['checkpoints']) for s in st['states']),
        st['flush_actions'], len(st['node_sublevel']), st['nodes_ambiguous_or_unassigned'],
        ', '.join(k for k, v in st['sublevels'].items() if v['hidden_outside_matinee']) or 'none'))
    # blockers
    inv = sqlite3.connect(os.path.join(AT, 'manifests', 'inventory.db'))
    dec = {f.rsplit('.', 2)[-2].lower() for f in os.listdir(os.path.join(REB, 'RE-Workspace', 'work', 'script', 'decomp')) if f.endswith('.txt')}
    k = Counter()
    for p, cl in inv.execute('SELECT package, class FROM exports'):
        if p in subs: k[cl] += 1
    kis = [x for x in k if x.startswith(('Seq', 'TnSeq', 'HmSeq'))]
    cust = sorted(x for x in kis if 'Tn' in x or 'Hm' in x)
    nod = [x for x in cust if x.lower() not in dec]
    g = lambda *ns: ', '.join('%d %s' % (k[n], n) for n in ns if k[n])
    a('## 3. Blockers\n')
    a('1. **Kismet**: %d objects, %d classes, %d High Moon custom; no RE decomp file (by name, PROVISIONAL): %s. %s.' % (
        sum(k[x] for x in kis), len(kis), len(cust), ', '.join(nod) or 'none',
        g('SeqAct_TnPawnFactory', 'TnSeqVar_Character', 'Checkpoint', 'SeqAct_SetStreamingState', 'SeqAct_FlushLevelStreaming')))
    a('2. **Matinee**: %s.' % (g('InterpData', 'SeqAct_Interp', 'InterpGroupDirector', 'CameraActor') or 'none'))
    a('3. **FaceFX / dialog**: %s.' % (g('FaceFXAsset', 'InterpTrackFaceFX', 'HmAnimNotify_Dialog', 'HmSoundEventDialogGroup', 'SoundCue') or 'none'))
    m = json.load(open(os.path.join(md, 'materials.json'), encoding='utf-8')); keys = sorted(m)
    mats = {json.loads(l)['object_path'].lower() for l in open(os.path.join(AT, 'manifests', 'extracted', 'materials.jsonl'), encoding='utf-8')
            if json.loads(l).get('object_path')}
    compiled = set()
    for f in glob.glob(os.path.join(REB, 'Rebuild-Rendering', '**', 'materials_glsl.json'), recursive=True):
        try:
            d = json.load(open(f, encoding='utf-8')); compiled |= {x.lower() for x in (d.get('materials') if isinstance(d.get('materials'), dict) else d)}
        except Exception: pass
    rows = [{'material': x, 'mat_file': x.lower() in mats, 'compiled_somewhere': x.lower() in compiled} for x in keys]
    lp = os.path.join(AT, 'work', 'campaign_pilot', M + '_materials_for_rendering.json')
    json.dump({'map': M, 'materials': rows}, open(lp, 'w'), indent=1)
    a('4. **Materials for Rendering** (`work/campaign_pilot/%s_materials_for_rendering.json`): %d materials, %d with `.mat`, %d compiled '
      'somewhere -> **%d need a matc pass**.' % (M, len(rows), sum(r['mat_file'] for r in rows), sum(r['compiled_somewhere'] for r in rows),
                                                 sum(not r['compiled_somewhere'] for r in rows)))
    pend = [s for s in ('m05_bsp_default_faces', 'map_structure_audit') if s not in S or S[s][0] != 0]   # failed, or skipped (WFC_SKIP_STAGES)
    a('5. **Pending diagnostics**: %s.' % (', '.join(pend) + ' (grid fix later, Streets byte-identical as the gate)' if pend else 'none: m05 and the structure audit both ran'))
    sr = os.path.join(AT, 'manifests', 'next_map', 'campaign_starts_report.json')
    r = next((x for x in json.load(open(sr, encoding='utf-8'))['chapters'] if x['map'] == M), None) if os.path.exists(sr) else None
    if r:
        tri = r['off_walk_graph_triage']; fmt = lambda d: ', '.join('%d %s' % (v, k) for k, v in sorted(d.items())) or 'none'
        a('6. **Starts and walk graph** (`manifests/next_map/campaign_starts_report.json`, backlog 5): %d starts (%d campaign starts + %d checkpoints), '
          '%d / %d on reachable floor; walk graph %s m2 (audit %s); pickups on reachable floor %s / %s; vs_validate ground check (reported only) '
          '%d grounded / %d airborne of the %d it checks.' % (r['starts'], r['campaign_player_starts'], r['checkpoints'], r['starts_on_reachable_floor'] or 0,
          r['starts'], '{:,.0f}'.format(r['walk_graph_area_m2'] or 0), r['structure_audit'], r['pickups_on_reachable_floor'], r['pickups'],
          r['ground_check']['grounded'], r['ground_check']['airborne'], r['ground_check']['checked']))
        a('   - Triage of what is off the walk graph (categories in `campaign_starts_report.py`): starts: %s; pickups: %s. airborne_by_design = real '
          'level data (fly-only reach specs, PROVISIONAL flag meaning); on_mover = audit limit (no mover collision in the walk graph); '
          'no_floor_below = UNKNOWN; unclassified = walk-rule limit (no jump / transform) or an unconnected floor, per-actor look needed.' % (
          fmt(tri.get('start', {})), fmt(tri.get('pickup', {}))))
    if notes and os.path.exists(notes): a('\n## 4. Notes\n\n' + open(notes, encoding='utf-8').read().strip())
    out = os.path.join(AT, 'docs', 'handoff', 'CAMPAIGN_PILOT_%s.md' % M)
    open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n'); print(out, '%.1f min, peak %.2f GB' % (total / 60, peak))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
