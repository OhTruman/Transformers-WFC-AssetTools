"""Campaign pipeline summary across all chapters (Integration 2026-10-16): per-chapter table and blocker totals, computed from the
chapter runs (campaign_chapter_doc.py's sources). The prose sections (plan, provisional items, recommended order) come from
docs/handoff/campaign_summary_notes.md.

  python campaign_summary.py   -> docs/handoff/CAMPAIGN_PIPELINE_SUMMARY.md
"""
import glob, json, os, sqlite3, sys, time
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import campaign_chapter_doc as D  # noqa: E402
AT, REB, VSR = D.AT, D.REB, D.VSR
CHAPTERS = ['A1_IAC', 'A2_KON', 'A3_COR', 'A4_ORB', 'A5_TRY', 'D1_ORB', 'D2_COR', 'D3A_IAC', 'D3B_IAC', 'D5_OME']

def main():
    inv = sqlite3.connect(os.path.join(AT, 'manifests', 'inventory.db'))
    dec = {f.rsplit('.', 2)[-2].lower() for f in os.listdir(os.path.join(REB, 'RE-Workspace', 'work', 'script', 'decomp')) if f.endswith('.txt')}
    exports = {}
    for p, cl in inv.execute('SELECT package, class FROM exports'): exports.setdefault(p, Counter())[cl] += 1
    rows, nodec, tot, mats_need, mats_all = [], {}, Counter(), set(), set()
    for M in CHAPTERS:
        md = os.path.join(VSR, 'Maps', M); mj = json.load(open(os.path.join(md, 'map.json'), encoding='utf-8'))
        st = json.load(open(os.path.join(md, 'streaming.json'), encoding='utf-8'))
        comp = json.load(open(os.path.join(AT, 'manifests', 'maps', M, 'completeness.json'), encoding='utf-8'))
        nav = json.load(open(os.path.join(md, 'navigation.json'), encoding='utf-8'))
        S = D.stages(M)
        k = Counter()
        for lv in mj['sublevels']: k.update(exports.get(lv, Counter()))
        kis = [x for x in k if x.startswith(('Seq', 'TnSeq', 'HmSeq'))]
        for x in kis:
            if ('Tn' in x or 'Hm' in x) and x.lower() not in dec: nodec.setdefault(x, []).append(M)
        pts = mj['spawn_and_gameplay_points']
        pick = sum(v for c, v in pts.items() if 'PickupFactory' in c)
        for c in ('InterpData', 'SeqAct_Interp', 'InterpGroupDirector', 'CameraActor', 'FaceFXAsset', 'InterpTrackFaceFX', 'HmAnimNotify_Dialog',
                  'SeqAct_TnPawnFactory', 'TnSeqVar_Character', 'Checkpoint', 'SeqAct_SetStreamingState'):
            tot[c] += k[c]
        tot['kismet'] += sum(k[x] for x in kis); tot['pickup factories (spawnpoints)'] += pick
        ml = json.load(open(os.path.join(AT, 'work', 'campaign_pilot', M + '_materials_for_rendering.json'), encoding='utf-8'))['materials']
        need = [r['material'] for r in ml if not r['compiled_somewhere']]; mats_need |= set(need); mats_all |= {r['material'] for r in ml}
        rows.append(dict(M=M, levels=len(mj['sublevels']), wall=sum(v[1] for s_, v in S.items() if s_ not in ('m05_bsp_default_faces', 'map_structure_audit')) / 60, peak=max((v[2] for s, v in S.items()
                         if s not in ('m05_bsp_default_faces', 'map_structure_audit')), default=0),
                         complete=sum(1 for v in comp['checks'].values() if v.get('status') == 'COMPLETE'), meshless=mj['props_missing_mesh'],
                         placed=mj['placed_props'], nav=len(nav.get('nodes') or []), states=len(st['states']), kismet=sum(k[x] for x in kis),
                         interp=k['InterpData'], facefx=k['FaceFXAsset'], pick=pick, matc=len(need), mats=len(ml)))
    diag = []
    for r in rows:
        M = r['M']; f05 = os.path.join(AT, 'manifests', 'next_map', M + '_bsp_default_faces.json')
        fsa = os.path.join(AT, 'manifests', 'maps', M, 'structure_audit.json')
        c05 = json.load(open(f05, encoding='utf-8'))['counts'] if os.path.exists(f05) else {}
        sa = json.load(open(fsa, encoding='utf-8')) if os.path.exists(fsa) else {}
        nlev = len({x.get('level') for x in json.load(open(f05, encoding='utf-8')).get('nodes', [])}) if os.path.exists(f05) else 0
        diag.append((M, c05.get('nodes'), nlev, c05.get('by_verdict'), c05.get('visible_in_play'), c05.get('visible_in_play_area_m2'),
                     (sa.get('verdict') or {}).get('status') if isinstance(sa.get('verdict'), dict) else sa.get('status'),
                     (sa.get('method') or {}).get('cell_m')))
    L = []; a = L.append
    a('# Campaign pipeline summary: all 10 chapters (%s, PROVISIONAL)\n' % time.strftime('%Y-%m-%d'))
    a('Generated by `scripts/wfc/campaign_summary.py` from the chapter runs (per-chapter docs: `CAMPAIGN_PILOT_<chapter>.md`). Every chapter '
      'ran through the generic map pipeline into `AssetTools/work/campaign_pilot` (CPU only, 10 GB cap, hold-aware); ExtractedAssets / '
      'Game Dump untouched. Wall time and peak = the last run of each export stage; the two pending diagnostics (m05, structure audit) are excluded from both.\n')
    a('## 1. Per chapter\n')
    a('| chapter | levels | wall min | peak GB | COMPLETE /46 | placed meshes | mesh-less | nav nodes | streaming states | Kismet objects | InterpData | FaceFX | pickup factories | matc needed / materials |')
    a('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for r in rows:
        a('| %(M)s | %(levels)d | %(wall).1f | %(peak).2f | %(complete)d | %(placed)d | %(meshless)d | %(nav)d | %(states)d | %(kismet)d | %(interp)d | %(facefx)d | %(pick)d | %(matc)d / %(mats)d |' % r)
    s = lambda k: sum(r[k] for r in rows)
    a('| **total** | %d | %.1f | | | %d | %d | %d | %d | %d | %d | %d | %d | %d unique / %d unique |\n' % (
        s('levels'), s('wall'), s('placed'), s('meshless'), s('nav'), s('states'), s('kismet'), s('interp'), s('facefx'), s('pick'), len(mats_need), len(mats_all)))
    a('## 1b. Diagnostics (m05 default-material BSP faces over all BSP levels, tiled; structure audit at a 2 m cell)\n')
    a('| chapter | default-material faces | levels with them | by verdict | visible in play | visible area m2 | structure audit | audit cell m |')
    a('|---|---|---|---|---|---|---|---|')
    for d_ in diag: a('| %s | %s | %s | %s | %s | %s | %s | %s |' % d_)
    a('')
    sr = os.path.join(AT, 'manifests', 'next_map', 'campaign_starts_report.json')
    if os.path.exists(sr):
        a('## 1c. Starts and walk graph (backlog 5; `campaign_starts_report.py`, campaign-mode ground check reported only)\n')
        a('| chapter | starts (campaign + checkpoint) | on reachable floor | walk graph m2 | pickups on reachable floor | audit (raw) | campaign verdict | airborne starts (exempt) | elevated starts (exempt) | off-graph starts (triage) | off-graph pickups (triage) |')
        a('|---|---|---|---|---|---|---|---|---|---|---|')
        fmt = lambda d: ', '.join('%d %s' % (v, k) for k, v in sorted(d.items())) or '-'
        for r in json.load(open(sr, encoding='utf-8'))['chapters']:
            cv = r['campaign_verdict']
            a('| %s | %d (%d + %d) | %s / %d | %s | %s / %s | %s | %s%s | %d | %d | %s | %s |' % (r['map'], r['starts'], r['campaign_player_starts'], r['checkpoints'],
              r['starts_on_reachable_floor'], r['starts'], '{:,.0f}'.format(r['walk_graph_area_m2'] or 0), r['pickups_on_reachable_floor'], r['pickups'],
              r['structure_audit'], cv['status'], ' (PROVISIONAL)' if cv['exemption_applied'] else '', cv['airborne_starts_exempt'], cv.get('elevated_starts_exempt', 0),
              fmt(r['off_walk_graph_triage'].get('start', {})), fmt(r['off_walk_graph_triage'].get('pickup', {}))))
        a('\nCampaign verdict = the audit verdict with airborne_by_design and elevated_above_floor starts exempt (level design; Integration 2026-10-17 / 18). '
          'PROVISIONAL where the exemption decides it: reachFlags 2 is read as R_FLY until RE confirms the enum. Unclassified starts still count.')
        a('\nTriage: airborne_by_design = real level data (fly-only reach specs, R_FLY PROVISIONAL); on_mover = audit limit (no mover '
          'collision in the walk graph); no_floor_below = UNKNOWN; unclassified = walk-rule limit or unconnected floor (per-actor look).\n')
    if all(os.path.exists(os.path.join(AT, 'manifests', 'next_map', M + '_matinee.json')) for M in CHAPTERS):
        a('## 1d. Matinee export (`vs_matinee.py`; schema `CAMPAIGN_MATINEE_SCHEMA.md`)\n')
        a('| chapter | InterpData | played | SeqAct_Interp | groups | director | bound | bound_runtime | empty_link | no_link | unresolved | Move | Director | Sound+Dialog | Event | AnimControl | FaceFX |')
        a('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        T = Counter()
        for M in CHAPTERS:
            c = json.load(open(os.path.join(AT, 'manifests', 'next_map', M + '_matinee.json'), encoding='utf-8'))['counts']
            gb = c.get('group_binding') or {}; tb = c['tracks_by_class']
            row = [c['interp_data'], c['played'], c['seqact_interp'], c['groups'], c['director_groups'], gb.get('bound', 0), gb.get('bound_runtime', 0),
                   gb.get('empty_link', 0), gb.get('no_link', 0), gb.get('unresolved', 0), tb.get('InterpTrackMove', 0), tb.get('InterpTrackDirector', 0),
                   tb.get('InterpTrackSound', 0) + tb.get('InterpTrackDialog', 0), tb.get('InterpTrackEvent', 0), tb.get('InterpTrackAnimControl', 0), tb.get('InterpTrackFaceFX', 0)]
            T.update(dict(enumerate(row)))
            a('| %s | %s |' % (M, ' | '.join(str(x) for x in row)))
        a('| **total** | %s |\n' % ' | '.join(str(T[i]) for i in range(16)))
    if all(os.path.exists(os.path.join(AT, 'manifests', 'next_map', M + '_dialog.json')) for M in CHAPTERS):
        a('## 1e. Dialog manifest (`vs_dialog.py`; schema `CAMPAIGN_DIALOG_SCHEMA.md`)\n')
        cols = ['conversations', 'lines', 'lines_speaker_bound', 'lines_without_wave', 'waves_with_int_subtitles', 'waves_fra_only', 'waves_without_subtitles',
                'waves_with_facefx', 'conversations_with_firing_event', 'anim_notify_copies', 'anim_notifies_distinct', 'anim_notifies_unmatched', 'sound_events', 'dialog_groups']
        a('| chapter | ' + ' | '.join(c.replace('_', ' ') for c in cols) + ' |'); a('|---' * (len(cols) + 1) + '|')
        T = Counter()
        for M in CHAPTERS:
            c = json.load(open(os.path.join(AT, 'manifests', 'next_map', M + '_dialog.json'), encoding='utf-8'))['counts']
            T.update({k: c.get(k, 0) for k in cols}); a('| %s | %s |' % (M, ' | '.join(str(c.get(k, 0)) for k in cols)))
        a('| **total** | %s |\n' % ' | '.join(str(T[k]) for k in cols))
        a('Anim-notify "distinct" is per chapter: the same animation notify is cooked into several chapters. Sound events and dialog groups are shared '
          'banks, so the per-chapter numbers overlap too.\n')
    a('## 2. Blocker classes (totals over the 10 chapters)\n')
    a('- **Kismet**: %d objects; High Moon custom classes with no RE decomp file (by file name, PROVISIONAL), with the chapters using them:' % tot['kismet'])
    for x in sorted(nodec, key=lambda x: (-len(nodec[x]), x)): a('  - `%s`: %d chapters (%s)' % (x, len(nodec[x]), ', '.join(nodec[x])))
    a('  - volume: %d SeqAct_TnPawnFactory, %d TnSeqVar_Character, %d Checkpoint, %d SeqAct_SetStreamingState.' % (
        tot['SeqAct_TnPawnFactory'], tot['TnSeqVar_Character'], tot['Checkpoint'], tot['SeqAct_SetStreamingState']))
    a('- **Matinee**: %d InterpData / %d SeqAct_Interp, %d director groups, %d CameraActor.' % (tot['InterpData'], tot['SeqAct_Interp'], tot['InterpGroupDirector'], tot['CameraActor']))
    a('- **FaceFX / dialog**: %d FaceFXAsset, %d InterpTrackFaceFX (cutscene lip-sync), %d HmAnimNotify_Dialog (in-game dialog, no lip-sync data).' % (
        tot['FaceFXAsset'], tot['InterpTrackFaceFX'], tot['HmAnimNotify_Dialog']))
    a('- **Pickup factories**: %d placed (spawnpoints.json); `vs_pickups` exports 0 of them in the campaign (backlog 1).' % tot['pickup factories (spawnpoints)'])
    a('- **Materials needing a matc pass** (not compiled in any Rendering `materials_glsl.json`): %d unique of %d unique campaign materials; per-chapter lists '
      '`work/campaign_pilot/<chapter>_materials_for_rendering.json`.\n' % (len(mats_need), len(mats_all)))
    json.dump(sorted(mats_need), open(os.path.join(AT, 'work', 'campaign_pilot', 'ALL_materials_needing_matc.json'), 'w'), indent=1)
    notes = os.path.join(AT, 'docs', 'handoff', 'campaign_summary_notes.md')
    if os.path.exists(notes): a(open(notes, encoding='utf-8').read().strip())
    out = os.path.join(AT, 'docs', 'handoff', 'CAMPAIGN_PIPELINE_SUMMARY.md')
    open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n'); print(out)
    for r in rows: print(r)

if __name__ == '__main__':
    main()
