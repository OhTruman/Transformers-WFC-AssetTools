"""Escalation weapon values for Gameplay E2b (2026-10-23): per weapon class Escalation can hand a player, the escalation player data
WEPDATA's values in the data/gameplay/weapons_mp.json field set. Same rule as Gameplay's work/pass22/weapons_mp.js: the class defaults
(HM_Engine.Default__HmWeaponData, then TransGame.Default__TnWeaponData) overlaid with the WEPDATA's authored properties (authored.db).
The data object per class is manifests/escalation/survival_weapon_data.json escalation_player_data (SurvivalData, else the PlayerData
GivenTo fallback: RE MP_ESCALATION_RE.md section 7.4). Every field of the weapons_mp.json field set is present; absent ones are null.

Classes: the inventory_type of every weapon_pickups entry of both Escalation maps, TnWeaponAssaultRifle (SetPlayerDefaults loadout),
the grenade bags (Flak / FlashBang / Heal / KamikazeMines), TnWeaponHeavyRocketTurret, TnWeaponGatlingGun.
Output: manifests/escalation/escalation_weapons.json
"""
import json, os, sqlite3
from collections import OrderedDict as OD
HERE = os.path.dirname(os.path.abspath(__file__)); AT = os.path.abspath(os.path.join(HERE, '..', '..')); TR = os.path.dirname(AT)
DB = sqlite3.connect(os.path.join(AT, 'manifests', 'authored.db'))
EXTRA = ['TnWeaponAssaultRifle', 'TnWeaponFlakGrenades', 'TnWeaponFlashBangs', 'TnWeaponHealGrenades', 'TnWeaponKamikazeMines',
         'TnWeaponHeavyRocketTurret', 'TnWeaponGatlingGun']

def get(op):
    r = DB.execute('select class, props from objects where opath=?', (op,)).fetchone()
    return (r[0], json.loads(r[1] or '{}')) if r else (None, None)

def main():
    defaults = {}
    for d in ('HM_Engine.Default__HmWeaponData', 'TransGame.Default__TnWeaponData'):
        c, p = get(d)
        if p: defaults.update(p)
    mp = json.load(open(os.path.join(TR, 'Rebuild', 'data', 'gameplay', 'weapons_mp.json'), encoding='utf-8'))['weapons']
    fields = sorted({k for w in mp.values() for d in ('MultiplayerData', 'PlayerData') if (w.get(d) or {}).get('values') for k in w[d]['values']} | set(defaults))
    surv = {w['weapon_class']: w for w in json.load(open(os.path.join(AT, 'manifests', 'escalation', 'survival_weapon_data.json'), encoding='utf-8'))['weapons']}
    want = []
    for m in ('MP_ESC_BrokenHope', 'MP_ESC_Remnant'):
        for p in json.load(open(os.path.join(AT, 'manifests', 'maps', m, 'escalation_geometry.json'), encoding='utf-8'))['weapon_pickups']:
            c = (p.get('inventory_type') or '').split('.')[-1]
            if c and c not in want: want.append(c)
    for c in EXTRA:
        if c not in want: want.append(c)
    out = OD(); missing = []
    for c in want:
        s = surv.get(c)
        if not s: missing.append(c); out['TransContent.' + c] = OD([('class', 'TransContent.' + c), ('escalation_data', None), ('note', 'not in survival_weapon_data.json')]); continue
        op = s.get('escalation_player_data'); cls, p = get(op) if op else (None, None)
        vals = None
        if p is not None:
            merged = dict(defaults); merged.update(p)
            vals = OD((k, merged.get(k)) for k in fields)
            for k in sorted(set(merged) - set(fields)): vals[k] = merged[k]          # authored fields outside the MP field set, kept
        out['TransContent.' + c] = OD([
            ('class', 'TransContent.' + c), ('cdo', s.get('cdo')),
            ('escalation_data', OD([('object', op), ('object_class', cls), ('source', s.get('escalation_player_data_source')), ('values', vals)]) if op else None),
            ('DefaultPickupAmount', (vals or {}).get('DefaultPickupAmount')),
            ('SurvivalData', s.get('SurvivalData')), ('PlayerData', s.get('PlayerData')), ('MultiplayerData', s.get('MultiplayerData')),
            ('escalation_ai_data', s.get('escalation_ai_data')),
            ('in_weapons_mp', ('TransContent.' + c) in mp)])
    json.dump(OD([('source', 'AssetTools authored.db (read-only): survival_weapon_data.json escalation_player_data objects over the class defaults '
                             '(HmWeaponData, TnWeaponData), the weapons_mp.js rule; generated by AssetTools/work/escalation_characters/escalation_weapons.py'),
                  ('rule', 'Escalation player weapons use SurvivalData (DesiredWeaponDataType 4) else PlayerData (TnWeapon.GivenTo fallback), never '
                           'MultiplayerData: RE MP_ESCALATION_RE.md sections 1 / 7.4'),
                  ('field_set', 'every key of data/gameplay/weapons_mp.json values + the class defaults (%d); absent = null' % len(fields)),
                  ('defaults_from', len(defaults)), ('classes', len(out)), ('missing_from_survival_data', missing), ('weapons', out)]),
              open(os.path.join(AT, 'manifests', 'escalation', 'escalation_weapons.json'), 'w', encoding='utf-8'), indent=1)
    print('classes', len(out), 'missing', missing, 'fields', len(fields))
    for k, v in out.items():
        e = v.get('escalation_data') or {}; x = e.get('values') or {}
        print('  %-44s %-34s pickup %-5s clip %-4s reserve %-5s dmg %s' % (k.split('.')[-1], (e.get('source') or '')[:34], v.get('DefaultPickupAmount'),
              x.get('MaxAmmoClipCount'), x.get('InitialReserveAmmoCount'), json.dumps(x.get('InstantHitDamage'))[:24]))

if __name__ == '__main__':
    main()
